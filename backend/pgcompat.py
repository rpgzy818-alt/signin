"""SQL 方言适配层：让同一套调用方代码跑在 SQLite 与 PostgreSQL 上。

设计原则（对应开发规范「一个能力一个入口」）：
- 所有方言差异收在本文件，router / deps / db 的业务 SQL 一行不改。
- 通过 DB_BACKEND 环境变量切换（sqlite / postgres），默认 sqlite，
  所以切库前的行为与现状完全一致——可先验证零回归，再切 PG。
- 只做「转换」，不做「抽象」：不引入 ORM，保持裸 SQL 的可读性与可调试性。

转换清单（经全仓扫描确认，见 P1 调研）：
1. 参数占位符 ? -> %s，只转单引号外的 ?（字符串字面量里的 ? 不动）
2. IFNULL -> COALESCE（PG 无 IFNULL）
3. INSERT OR IGNORE -> INSERT ... ON CONFLICT DO NOTHING
4. 行对象：sqlite3.Row 与 psycopg2 RealDictRow 都支持 r["col"]，
   统一再补一个 .get() 能力以兼容 dict 风格访问
5. lastrowid：sqlite 用 cursor.lastrowid，PG 需 RETURNING id
"""
import os
import re

DB_BACKEND = os.environ.get("DB_BACKEND", "sqlite").lower()


def _convert_placeholders(sql: str) -> str:
    """把单引号外的 ? 换成 %s；单引号内（含转义 ''）原样保留。

    扫描全仓后确认：LIKE 的 % 在绑定参数值里（不在 SQL 文本里），
    字符串字面量里没有 ?，所以这个转换是安全的。
    """
    if DB_BACKEND != "postgres":
        return sql
    out = []
    in_str = False
    i = 0
    while i < len(sql):
        ch = sql[i]
        if ch == "'":
            # SQL 里转义的单引号是 ''——视为字面量内的一对，不切换状态
            if in_str and i + 1 < len(sql) and sql[i + 1] == "'":
                out.append("''")
                i += 2
                continue
            in_str = not in_str
            out.append(ch)
        elif ch == "?" and not in_str:
            out.append("%s")
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def convert_sql(sql: str) -> str:
    """对单条 SQL 做全部方言转换。INSERT OR IGNORE 需带列名，单独在下面处理。"""
    s = _convert_placeholders(sql)
    if DB_BACKEND == "postgres":
        s = re.sub(r"\bIFNULL\s*\(", "COALESCE(", s, flags=re.IGNORECASE)
        # SQLite 允许 IS NOT <数字>；PG 不支持，等价于 !=
        s = re.sub(r"\bIS\s+NOT\s+(\d)", r"!= \1", s, flags=re.IGNORECASE)
        s = re.sub(r"\bIS\s+(\d)", r"= \1", s, flags=re.IGNORECASE)
    return s


def convert_insert_ignore(sql: str) -> str:
    """INSERT OR IGNORE INTO t (...) VALUES (...) -> ... ON CONFLICT DO NOTHING。

    只处理全仓出现的一种形态（seed staff）。不匹配时原样返回，
    绝不猜——猜错的代价比漏转高。
    """
    s = convert_sql(sql)
    if DB_BACKEND == "postgres":
        s = re.sub(
            r"^INSERT\s+OR\s+IGNORE\s+INTO\s+",
            "INSERT INTO ",
            s,
            flags=re.IGNORECASE,
        )
        # 追加 ON CONFLICT DO NOTHING（去掉末尾可能的分号）
        stripped = s.rstrip().rstrip(";")
        if "ON CONFLICT" not in stripped.upper():
            s = stripped + " ON CONFLICT DO NOTHING"
    return s


def ddl_for_backend(sqlite_ddl: str) -> str:
    """建表 DDL：SQLite 的 AUTOINCREMENT 在 PG 用 GENERATED BY DEFAULT AS IDENTITY。"""
    if DB_BACKEND != "postgres":
        return sqlite_ddl
    return re.sub(
        r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sqlite_ddl,
        flags=re.IGNORECASE,
    )


class CompatRow(tuple):
    """同时支持 r[0] 位置访问、r["col"] 键访问、dict(r) 转字典。

    sqlite3.Row 就具备这三种能力；PG 的 RealDictRow 只支持键访问，
    会让全仓 21 处 fetchone()[0] 崩溃。本类补齐，使 router 一行不改。
    """

    def __new__(cls, values, columns):
        obj = super().__new__(cls, values)
        obj._columns = tuple(columns)
        obj._mapping = dict(zip(obj._columns, values))
        return obj

    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple.__getitem__(self, key)
        return self._mapping[key]

    def keys(self):
        return self._columns

    def get(self, key, default=None):
        return self._mapping.get(key, default)

    def __contains__(self, key):
        return key in self._mapping


def _make_compat_cursor():
    """构造产出 CompatRow 的 cursor 子类（psycopg2 用 cursor_factory 而非 row_factory）。"""
    from psycopg2.extensions import cursor as BaseCursor

    class CompatCursor(BaseCursor):
        def fetchone(self):
            row = super().fetchone()
            if row is None or isinstance(row, CompatRow):
                return row
            cols = [d[0] for d in self.description] if self.description else []
            return CompatRow(row, cols)

        def fetchall(self):
            rows = super().fetchall()
            if not rows or isinstance(rows[0], CompatRow):
                return rows
            cols = [d[0] for d in self.description] if self.description else []
            return [CompatRow(r, cols) for r in rows]

        def fetchmany(self, size=None):
            rows = super().fetchmany(size)
            if not rows or isinstance(rows[0], CompatRow):
                return rows
            cols = [d[0] for d in self.description] if self.description else []
            return [CompatRow(r, cols) for r in rows]

        def __iter__(self):
            # 不用 super().__iter__()——psycopg2 的实现内部会回调 self 的迭代，
            # 与重写的方法相互递归。改为显式循环调用已兼容的 fetchone()。
            while True:
                row = self.fetchone()
                if row is None:
                    break
                yield row

    return CompatCursor


def connect_postgres(dsn):
    """PG 连接：用 CompatCursor 对齐 sqlite3.Row 的三种访问方式。"""
    import psycopg2
    conn = psycopg2.connect(dsn)
    conn.cursor_factory = _make_compat_cursor()
    return conn


def insert_and_get_id(proxy, table, cols, values):
    """PG 版插入并取回自增 id（psycopg2 无 lastrowid，必须 RETURNING）。

    cols/values 已由调用方按同序排好；返回新行 id。
    """
    placeholders = ", ".join(["%s"] * len(cols))
    sql = "INSERT INTO %s (%s) VALUES (%s) RETURNING id" % (
        table, ", ".join(cols), placeholders,
    )
    cur = proxy.execute(sql, list(values))
    row = cur.fetchone()
    return row["id"] if row else None


class ConnProxy:
    """连接代理：SQLite 模式纯透传，PG 模式在 execute 边界转方言。

    router 全部 122 处 conn.execute 都经由此处，因此业务 SQL 一行不改。
    代理只拦截需要转换的方法，其余属性（commit/rollback/row_factory 等）
    直接透传给底层连接。
    """

    def __init__(self, real_conn):
        object.__setattr__(self, "_real", real_conn)
        # 已写进 PG 会话变量的活动/机构 id，用于跳过重复 SET。
        # commit/rollback 后会清空——普通 SET 属于事务，回滚会把它一起撤销，
        # 不清标记就会出现「以为设过了，其实已被回滚」的静默串数据。
        object.__setattr__(self, "_act_id", None)
        object.__setattr__(self, "_org_id", None)

    def _sync_activity(self, cur):
        """把当前请求的活动与机构写进 PG 会话变量，供行级安全策略读取。

        这是 RLS 生效的前提。漏了它策略会 fail-closed（查不到任何行），
        比串数据安全，但会表现为「页面全空」，所以每次 execute 都校验一次。

        **机构从当前活动推导**（A 批）：活动已由中间件解析并校验归属，
        它属于哪个机构，本次请求就按那个机构隔离。机构不来自前端声明——
        前端只能选活动，活动到机构的映射在数据库里，前端改不了。
        """
        import activity as _activity
        aid = _activity.current_id()
        act = _activity.current()
        org_id = int(act.org_id) if (act is not None and act.org_id) else 1
        if object.__getattribute__(self, "_act_id") != aid:
            cur.execute("SET app.activity_id = %s", (str(aid),))
            object.__setattr__(self, "_act_id", aid)
        if object.__getattribute__(self, "_org_id") != org_id:
            cur.execute("SET app.org_id = %s", (str(org_id),))
            object.__setattr__(self, "_org_id", org_id)

    def execute(self, sql, params=()):
        real = object.__getattribute__(self, "_real")
        if DB_BACKEND == "postgres":
            sql = convert_insert_ignore(sql) if "INSERT OR IGNORE" in sql.upper() else convert_sql(sql)
            # 每次新建 cursor：对齐 sqlite3 conn.execute() 返回独立游标的语义，
            # 避免嵌套/交错查询时前一个 cursor 结果被覆盖。
            cur = real.cursor()
            try:
                self._sync_activity(cur)
                cur.execute(sql, params)
            except Exception:
                # PG 语句失败后连接进入 aborted 状态，后续所有语句都会报
                # InFailedSqlTransaction。sqlite3 无此行为。这里自动 rollback
                # 把连接恢复到可用状态，再把原异常抛给上层（业务语义不变）。
                real.rollback()
                object.__setattr__(self, "_act_id", None)
                object.__setattr__(self, "_org_id", None)
                raise
            return cur
        return real.execute(sql, params)

    def executemany(self, sql, params):
        real = object.__getattribute__(self, "_real")
        if DB_BACKEND == "postgres":
            sql = convert_sql(sql)
            cur = real.cursor()
            self._sync_activity(cur)
            cur.executemany(sql, params)
            return cur
        return real.executemany(sql, params)

    def commit(self):
        real = object.__getattribute__(self, "_real")
        real.commit()
        object.__setattr__(self, "_act_id", None)
        object.__setattr__(self, "_org_id", None)

    def rollback(self):
        real = object.__getattribute__(self, "_real")
        real.rollback()
        object.__setattr__(self, "_act_id", None)
        object.__setattr__(self, "_org_id", None)

    def __getattr__(self, name):
        return getattr(object.__getattribute__(self, "_real"), name)
